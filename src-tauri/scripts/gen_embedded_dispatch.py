#!/usr/bin/env python3
"""Generates src/embedded/dispatch.rs from the Tauri command list in src/lib.rs.

PROGRAMERI POS Mobile hosts Mjeku in-process (no Tauri runtime). The desktop build keeps using
tauri::generate_handler!; the embedded build uses this generated dispatcher, which calls the
SAME command functions with the same argument names (camelCase keys, like Tauri's default).
Run after adding/removing/changing a #[tauri::command]:  python scripts/gen_embedded_dispatch.py
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LIB = ROOT / "src" / "lib.rs"
OUT = ROOT / "src" / "embedded" / "dispatch.rs"

src = LIB.read_text(encoding="utf-8")

m = re.search(r"generate_handler!\[(.*?)\]\)", src, re.S)
if not m:
    sys.exit("generate_handler! list not found")
handler = [x.strip() for x in m.group(1).split(",")]
handler = [re.sub(r"//.*", "", x).strip() for x in handler]
handler = [x for x in handler if x]


def split_top(s, sep=","):
    out, depth, cur = [], 0, ""
    for ch in s:
        if ch in "<([{":
            depth += 1
        elif ch in ">)]}":
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]


def camel(n):
    parts = n.split("_")
    return parts[0] + "".join(p[:1].upper() + p[1:] for p in parts[1:])


def find_fn(name):
    # attribute line(s) then optional cfg lines then fn
    pat = re.compile(
        r"(#\[(?:cfg_attr\([^\]]*tauri::command[^\]]*\)|tauri::command[^\]]*)\]\s*(?:#\[[^\]]*\]\s*)*)"
        r"(pub(?:\(crate\))?\s+)?(async\s+)?fn\s+" + re.escape(name) + r"\s*(<[^>]*>)?\s*\(",
        re.S,
    )
    mm = pat.search(src)
    if not mm:
        sys.exit(f"command fn not found: {name}")
    attr = mm.group(1)
    is_async = bool(mm.group(3))
    # params: balanced parens from mm.end()-1
    i = mm.end()
    depth = 1
    j = i
    while depth:
        c = src[j]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
        j += 1
    params = src[i : j - 1]
    rest = src[j : j + 400]
    rm = re.match(r"\s*->\s*(.*?)\s*(\{|where)", rest, re.S)
    ret = rm.group(1).strip() if rm else "()"
    rename_snake = "rename_all" in attr and "snake_case" in attr
    return is_async, split_top(params), ret, rename_snake


lines = [
    "// @generated by scripts/gen_embedded_dispatch.py from src/lib.rs — DO NOT EDIT BY HAND.",
    "#![allow(unused_variables, clippy::all)]",
    "use super::{AppHandle, State, IntoResp};",
    "use crate::*;",
    "use serde_json::Value;",
    "",
    "pub const COMMANDS: &[&str] = &[",
]
for h in handler:
    lines.append(f'    "{h}",')
lines.append("];")
lines.append("")
lines.append(
    "pub async fn dispatch(app: &AppHandle, st: &'static AppState, cmd: &str, args: Value) -> Result<Value, Value> {"
)
lines.append("    match cmd {")

for h in handler:
    is_async, params, ret, snake = find_fn(h)
    call_args = []
    fields = []
    for p in params:
        if ":" not in p:
            sys.exit(f"{h}: bad param {p}")
        pname, ptype = [x.strip() for x in p.split(":", 1)]
        pname = pname.replace("mut ", "").strip()
        if "AppHandle" in ptype:
            call_args.append("app.clone()")
        elif re.search(r"\bState\s*<", ptype):
            call_args.append("State(st)")
        else:
            key = pname if snake else camel(pname)
            fields.append((pname, key, ptype))
            call_args.append(f"a.{pname}")
    body = []
    if fields:
        body.append("            #[derive(serde::Deserialize)]")
        body.append("            struct A {")
        for pname, key, ptype in fields:
            body.append(f'                #[serde(rename = "{key}")] {pname}: {ptype},')
        body.append("            }")
        body.append(
            "            let a: A = serde_json::from_value(if args.is_null() { Value::Object(Default::default()) } else { args })"
            ".map_err(|e| Value::String(format!(\"invalid args for "
            + h
            + ": {e}\")))?;"
        )
    call = f"{h}({', '.join(call_args)})" + (".await" if is_async else "")
    kind = "result" if ret.replace(" ", "").startswith("Result<") else "plain"
    if kind == "result":
        body.append(f"            IntoResp::into_resp({call})")
    else:
        body.append(f"            IntoResp::into_resp(Ok::<_, String>({call}))")
    lines.append(f'        "{h}" => {{')
    lines.extend(body)
    lines.append("        }")

lines.append('        other => Err(Value::String(format!("Komanda e panjohur: {other}"))),')
lines.append("    }")
lines.append("}")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{len(handler)} commands -> {OUT}")
